/** Hook that returns a `t` function scoped to the Market dictionary,
 * with `{placeholder}` interpolation support and language fallback. */
export function useMarketT() {
  const { language } = useLanguage();
  return (key: string, vars?: Record<string, string | number>) => {
    const raw =
      marketDict[language]?.[key] ??
      marketDict.en[key] ??
      marketDict.pt[key] ??
      key;
    if (!vars) return raw;
    return Object.keys(vars).reduce(
      (acc, k) => acc.split(`{${k}}`).join(String(vars[k])),
      raw,
    );
  };
}
